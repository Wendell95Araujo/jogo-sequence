function translate(key, params = {}) {
  let str;
  if (key.includes(".")) {
    const keys = key.split(".");
    str =
      keys.reduce((obj, i) => obj?.[i], translations[currentLanguage]) ??
      keys.reduce((obj, i) => obj?.[i], translations["en"]) ??
      key;
  } else {
    str =
      translations[currentLanguage?.toLowerCase()]?.[key] ??
      translations["en"]?.[key] ??
      key;
  }

  if (typeof str === "string") {
    for (const param in params) {
      str = str.replace(new RegExp(`{${param}}`, "g"), params[param]);
    }
  }
  return str;
}

function initializeTranslations() {
  let savedLang = null;
  try {
    savedLang = localStorage.getItem(LANGUAGE_STORAGE_KEY);
  } catch (e) {
    console.warn("Acesso ao localStorage negado:", e);
  }

  const urlParams = new URLSearchParams(window.location.search);
  const paramLang = urlParams.get("lang");

  const browserLang = (
    navigator.language ||
    navigator.userLanguage ||
    "pt"
  ).split("-")[0];

  currentLanguage = ["pt", "en", "es"].includes(paramLang)
    ? paramLang
    : ["pt", "en", "es"].includes(savedLang)
      ? savedLang
      : ["pt", "en", "es"].includes(browserLang)
        ? browserLang
        : "pt";

  if (paramLang && ["pt", "en", "es"].includes(paramLang)) {
    try { localStorage.setItem(LANGUAGE_STORAGE_KEY, paramLang); } catch (e) {}
  }

  document.documentElement.lang = currentLanguage;

  const translatedTitle = translate("pageTitle");
  const translatedDesc = translate("pageDescription");

  if (translatedTitle) {
    document.title = translatedTitle;
    const ogTitle = document.querySelector('meta[property="og:title"]');
    if (ogTitle) ogTitle.setAttribute("content", translatedTitle);
    const twTitle = document.querySelector('meta[name="twitter:title"]');
    if (twTitle) twTitle.setAttribute("content", translatedTitle);
  }

  if (translatedDesc) {
    const descriptionTag = document.querySelector('meta[name="description"]');
    if (descriptionTag) descriptionTag.setAttribute("content", translatedDesc);
    const ogDesc = document.querySelector('meta[property="og:description"]');
    if (ogDesc) ogDesc.setAttribute("content", translatedDesc);
    const twDesc = document.querySelector('meta[name="twitter:description"]');
    if (twDesc) twDesc.setAttribute("content", translatedDesc);
  }

  document.querySelectorAll("[data-translate-key]").forEach(el => {
    const key = el.dataset.translateKey;
    const translation = translate(key);
    if (translation && translation !== key) {
      el.innerHTML = translation;
    }
  });

  const attributeMaps = [
    { selector: "[data-translate-placeholder-key]", attr: "placeholder", dataKey: "translatePlaceholderKey" },
    { selector: "[data-translate-title-key]", attr: "title", dataKey: "translateTitleKey" },
    { selector: "[data-translate-aria-label-key]", attr: "aria-label", dataKey: "translateAriaLabelKey" },
  ];

  attributeMaps.forEach(({ selector, attr, dataKey }) => {
    document.querySelectorAll(selector).forEach(el => {
      const key = el.dataset[dataKey];
      const translation = translate(key);
      if (translation && translation !== key) {
        el.setAttribute(attr, translation);
      }
    });
  });
}
